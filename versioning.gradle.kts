import org.gradle.api.Project

/** Automatic versioning from git tags + version.properties fallback */

val versionProperties = file("version.properties")

// Read version from properties file or derive from git
var versionName: String
var versionCode: Int

if (versionProperties.exists()) {
    val props = java.util.Properties()
    versionProperties.inputStream().use { props.load(it) }
    versionName = props.getProperty("versionName", "1.0.0")
    versionCode = props.getProperty("versionCode", "1").toInt()
} else {
    // Try to derive from git tag
    val gitTag = try {
        val proc = ProcessBuilder("git", "describe", "--tags", "--abbrev=0").redirectErrorStream(true).start()
        proc.inputStream.bufferedReader().use { it.readText() }.trim()
    } catch (e: Exception) {
        null
    }
    versionName = gitTag?.removePrefix("v") ?: "1.0.0-SNAPSHOT"
    versionCode = try {
        val proc = ProcessBuilder("git", "rev-list", "--count", "HEAD").redirectErrorStream(true).start()
        proc.inputStream.bufferedReader().use { it.readText() }.trim().toInt()
    } catch (e: Exception) {
        1
    }
}

// Expose to all projects
project.extra["versionName"] = versionName
project.extra["versionCode"] = versionCode

// Task to update version.properties (for CI)
tasks.register("updateVersionProperties") {
    group = "versioning"
    description = "Updates version.properties from git"
    doLast {
        val tag = try {
            val proc = ProcessBuilder("git", "describe", "--tags", "--abbrev=0").redirectErrorStream(true).start()
            proc.inputStream.bufferedReader().use { it.readText() }.trim()
        } catch (e: Exception) {
            "v$versionName"
        }
        val count = try {
            val proc = ProcessBuilder("git", "rev-list", "--count", "HEAD").redirectErrorStream(true).start()
            proc.inputStream.bufferedReader().use { it.readText() }.trim().toInt()
        } catch (e: Exception) {
            versionCode
        }
        val commit = try {
            val proc = ProcessBuilder("git", "rev-parse", "--short", "HEAD").redirectErrorStream(true).start()
            proc.inputStream.bufferedReader().use { it.readText() }.trim()
        } catch (e: Exception) {
            "unknown"
        }
        val timestamp = java.time.Instant.now().toString()

        versionProperties.outputStream().use { out ->
            val props = java.util.Properties().apply {
                setProperty("versionName", tag.removePrefix("v"))
                setProperty("versionCode", count.toString())
                setProperty("buildTimestamp", timestamp)
                setProperty("gitCommit", commit)
                store(out, "Auto-generated by Gradle")
            }
        }
        println("Updated version.properties: ${tag.removePrefix("v")} ($count)")
    }
}